export function localizeError(message: string, locale: Locale): string {
  if (locale === 'es') return message
  for (const [pattern, replacement] of englishErrorReplacements) {
    if (pattern.test(message)) return replacement
  }

  return message
    .replace(/^“(.+)” es una clave del Query; configúrala en las condiciones de clave\.$/, '“$1” is a Query key; configure it in the key conditions.')
    .replace(/^La ruta “(.+)” no es válida\.$/, 'The path “$1” is invalid.')
    .replace(/^Operador no soportado: (.+)$/, 'Unsupported operator: $1')
    .replace(/^La clave “(.+)” requiere un valor (.+)\.$/, 'The key “$1” requires a $2 value.')
    .replace(/^“(.+)” no es un número válido de DynamoDB\.$/, '“$1” is not a valid DynamoDB number.')
    .replace(/^Falta la clave “(.+)”\.$/, 'The “$1” key is missing.')
    .replace(/^La clave “(.+)” tiene un tipo incorrecto\.$/, 'The “$1” key has an incorrect type.')
    .replace(/^El índice “(.+)” no tiene partition key\.$/, 'The “$1” index does not have a partition key.')
    .replace(/^Tipo de clave desconocido para “(.+)”\.$/, 'Unknown key type for “$1”.')
}
